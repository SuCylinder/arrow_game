"""箭头消除小游戏入口。

玩法：点击棋盘上的箭头，若它指向的方向到棋盘边界之间没有其它箭头，
它就从那个方向飞出棋盘消失；否则算碰撞，箭头原地晃动变红并扣一次失误。
清空全部箭头过关，进入下一关；失误用完失败，可以重开本关。

箭头分上、下、左、右四种方向，各占一个格子；路径检测只看同一行或
同一列、箭头与边界之间是否还有其它箭头。

扩展功能：
  6 个关卡与关卡选择（含锁定/解锁、星级与最好成绩）；
  计时、得分与三星评价；提示（H 键）高亮可飞箭头；
  撤销（Z 键）上一步成功飞出；AI 演示自动通关（不计成绩）；
  随机挑战（生成保证可通关的关卡）；进度存档到项目内 save.json。
"""

import pygame

from arrow.game import Game


def main():
    pygame.init()
    try:
        Game().run()
    finally:
        pygame.quit()


if __name__ == "__main__":
    main()
